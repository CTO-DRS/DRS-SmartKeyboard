package com.drs.smartkeyboard.ime.clipboard

/**
 * DRS v2.15.0 «ذاكرة الحافظة الأمينة» — بوابة التقاط الحافظة في السجل
 * المحلي الدائم.
 *
 * المشكلة التي أغلقها هذا العقد: ثلاث علات متشابكة في مسار التقاط
 * الحافظة، كلها من جنس العلة التي عالجتها v2.14.0 لذاكرة الإيموجي:
 *
 *  1. «العرض محجوب والالتقاط مفتوح» بالتماثل حرفيًا: زر اللصق يُعطَّل
 *     والجهاز مقفول (مقيّم السياق في KeyboardManager يرفض CLIPBOARD_PASTE
 *     عند isDeviceLocked/isKeyguardLocked)، ولوحة الحافظة تُعطّل أزرارها
 *     مقفولًا — بينما مسارا الالتقاط (onPrimaryClipChanged و
 *     insertOrMoveBeginning) لا يفحصان القفل إطلاقًا: مستمع الحافظة
 *     النظامي عالمي، وأي تغيير حافظة والقفل مرفوع كان يدخل السجل الدائم
 *     صامتًا.
 *
 *  2. إشعار «تعديل» المسروب: addNewClip كان يتجاهل قيمة إرجاع مسار
 *     التخزين — نسخةٌ في جلسة التخفي أو حقل كلمة مرور يُرفض تقاطُها في
 *     السجل لكن إشعار الرؤوس ينشر معاينة النص المرفوض رغم أن وثيقة
 *     السياسة نفسها تدّعي «التقاط مُبوَّب من الأصل»، وID الصف الذي
 *     يفتحه الإشعار غير موجود أصلًا (لا صف لأن الالتقاط رُفض).
 *
 *  3. بوابات متفرقة بلا عقد: فحوص الخصوصية كانت inline في موقعين
 *     يُكرران الشروط يدويًا (بوابة الاستنساخ المسبق وبوابة الإدراج)
 *     بلا جدول حقيقة يثبت اتساقهما — أي تعديل مستقبلي على أحدهما كان
 *     سينساب لانحراف صامت عن الآخر.
 *
 * الفلسفة نفسها: ما تنسخه في سياق خاص لا يترك أثرًا في ذاكرة الحافظة —
 * لا سحابة ولا تخمين، ولا التقاط صامت. واللصق ورقاقة الاقتراح فوق
 * المقص الدائم حق مشروع لا يُحكم هنا (عرضٌ لا التزام: يقرآن المقص
 * الحيّ ولا يخزنان شيئًا) — **التخزين الدائم هو الالتزام**، وهو وحده ما
 * تحكمه هذه البوابة، مع استنساخ الوسائط إلى القرص لأنه كتابةٌ دائمة.
 * الإدارة (التثبيت/الإزالة/التعديل/المسح/الاستيراد) لما هو محفوظ سلفًا
 * لا تمر بالبوابة.
 *
 * العقد نقي بلا Android إطلاقًا: المدخلات حقائق تُقرأ لحظة حدث الالتقاط،
 * والمخرج حكم من نوعين. ترتيب الأسباب مصمم ومثبت اختبارًا (جدول كامل
 * 32 تركيبة): سلّم الحماية من مَن يسأل إلى هل تريد الميزة أصلًا —
 * الجلسة (تخفي) ← الحقل (كلمة مرور) ← المحتوى (حساس) ← البيئة (قفل)
 * ← الميزة (سجل معطّل).
 */
object DrsClipboardCaptureGate {

    /** سبب الرفض — مرتب بترتيب الأولوية التصميمي (أقوى سبب أولًا). */
    enum class Refusal {
        /** جلسة خاصة (وضع التخفي) — لا ذاكرة لأي شيء يُنسخ هنا. */
        PRIVATE_SESSION,

        /** حقل كلمة مرور — ما تنسخه فيه لا يُلتقط أبدًا. */
        CREDENTIALS_FIELD,

        /** مقص حساس (EXTRA_IS_SENSITIVE) — المصدر علّمه سرًا فلا تخزين. */
        SENSITIVE_CLIP,

        /** القفل الشاشي مرفوع — اللصق محجوب فالالتقاط محجوب بالتماثل. */
        DEVICE_LOCKED,

        /** السجل نفسه معطّل من الإعدادات (clipboard__history_enabled). */
        HISTORY_DISABLED,
    }

    /** حكم البوابة: إما الالتقاط، أو الرفض بسبب واحدٍ صريح. */
    sealed interface Verdict {
        /** خزّن في السجل — كل الحقائق سليمة ولا سياق خاص. */
        data object Capture : Verdict

        /** ارفض التخزين صامتًا في الذاكرة — ولا استثناء ولا سجل أخطاء. */
        data class Refuse(val reason: Refusal) : Verdict
    }

    /**
     * حكم الالتقاط. كل الحقائق تُمرر صراحة — لا قراءة حالة كامنة داخل
     * البوابة، فالحكم حتمي بدوال مدخلاته واختباره جدول كامل بلا أثر
     * جانبي.
     *
     * ترتيب الفحص (مثبت اختبارًا واحدًا لكل زوج متجاور):
     * التخفي → كلمة المرور → الحساس → الجهاز مقفول → السجل معطّل → خزّن.
     */
    fun decide(
        historyEnabled: Boolean,
        isIncognitoMode: Boolean,
        isPasswordVariation: Boolean,
        isSensitiveClip: Boolean,
        isDeviceLocked: Boolean,
    ): Verdict {
        if (isIncognitoMode) return Verdict.Refuse(Refusal.PRIVATE_SESSION)
        if (isPasswordVariation) return Verdict.Refuse(Refusal.CREDENTIALS_FIELD)
        if (isSensitiveClip) return Verdict.Refuse(Refusal.SENSITIVE_CLIP)
        if (isDeviceLocked) return Verdict.Refuse(Refusal.DEVICE_LOCKED)
        if (!historyEnabled) return Verdict.Refuse(Refusal.HISTORY_DISABLED)
        return Verdict.Capture
    }

    /**
     * حقائق السياق وقت الالتقاط، تُبنى عند حدث النسخ نفسه (لا تُخزَّن ولا
     * تُتداول) — كل حقل بلا افتراضي، فلا مسار بناءٍ صامت يفتح باب
     * الالتقاط. حساسية المقص ليست هنا: إنها حقيقة المحتوى نفسه لا
     * البيئة، وتُمرر لـ[decide] من العنصر ذاته.
     */
    data class CaptureContext(
        val isIncognitoMode: Boolean,
        val isPasswordVariation: Boolean,
        val isDeviceLocked: Boolean,
    )

    /**
     * دلالة الرفض لمسار التخزين: متى يجب أن يعيد المُدرج «رُفض» ليتنفّس
     * المستدعي بتنظيف استنساخ وسائط ربما كوّنه قبل الحكم؟ أسباب الخصوصية
     * الأربعة ترفض التخزين فعلًا (false من المُدرج)، أما HISTORY_DISABLED
     * فلا شيء خُزِن ولا شيء يُنظَّف — سلوك التراث محفوظ حرفيًا (مع عطْل
     * السجل يُعاد true لأن استنساخ الوسائط الليفي يظل ظهرَ المقص الحي).
     */
    fun storageRefused(verdict: Verdict): Boolean {
        return verdict is Verdict.Refuse && verdict.reason != Refusal.HISTORY_DISABLED
    }

    /**
     * هل يجوز استنساخ وسائط إلى القرص (صف مزوّد + ملف ظهر) تحت هذا
     * الحكم؟ الاستنساخ كتابةٌ دائمة فهو التقاط: يُمنع تحت كل أسباب
     * الخصوصية. وتحت HISTORY_DISABLED يجوز — عمدًا: الاستنساخ بلا سجل
     * هو ظهر المقص الحي الدائم (سلوك v1.x الموروث: استمرارية الوسائط
     * للصق حي حتى مع السجل معطلًا)، وأيضلاعه كان سيقطع لصق الصور
     * والفيديو لمستخدمي أطفأ السجل.
     */
    fun allowsMediaClone(verdict: Verdict): Boolean {
        return when (verdict) {
            is Verdict.Capture -> true
            is Verdict.Refuse -> verdict.reason == Refusal.HISTORY_DISABLED
        }
    }
}
